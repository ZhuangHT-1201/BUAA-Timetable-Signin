export function localizeErrorMessage(message: string, language: Language): string {
  if (language === 'zh') return message;
  const exact = englishErrorMessages[message];
  if (exact) return exact;
  const campusHttp = /^校园服务返回 HTTP (\d+)。$/.exec(message);
  if (campusHttp) return `Campus service returned HTTP ${campusHttp[1]}.`;
  const classroomHttp = /^课堂服务返回 HTTP (\d+)。$/.exec(message);
  if (classroomHttp) return `Classroom service returned HTTP ${classroomHttp[1]}.`;
  return message;
}
